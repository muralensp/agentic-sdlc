"""PreToolUse hook written by `adlc`: refuse edits to the board and the protected areas.

Claude Code runs this before every Edit, Write, MultiEdit and NotebookEdit. It reads the tool call
on stdin and prints a deny decision as JSON, or nothing to allow. The patterns come from
`protected.json` next to this file, which `adlc` generates from the project's profile.

This is a second layer. A shell command can still write a protected file, so the orchestrator
checks the diff after every iteration and stops the task if it finds one. Do not edit this file by
hand: it is under `.claude/`, a protected area, so a change to it always goes to a person.
"""

import json
import posixpath
import re
import sys
from pathlib import Path

WRITERS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}
RULES = Path(__file__).with_name("protected.json")


def normal(path):
    path = path.replace(chr(92), "/")
    while path.startswith("./"):
        path = path[2:]
    return path


def glob(pattern):
    """`*` and `?` stay inside one folder, `**` crosses folders, the rest is literal."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$", re.IGNORECASE)


def relative(path, cwd):
    """The path from the project root, or the path as given when it is not inside it."""
    path, root = posixpath.normpath(normal(path)), posixpath.normpath(normal(cwd or "."))
    if re.match(r"^([A-Za-z]:)?/", path) and path.lower().startswith(
        root.lower().rstrip("/") + "/"
    ):
        return path[len(root.rstrip("/")) + 1 :]
    return path


def leaves_the_project(path):
    return (
        path.startswith("/") or re.match(r"^[A-Za-z]:", path) is not None or ".." in path.split("/")
    )


def deny(path, why):
    return {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": (
                f"{path} {why}. Only the orchestrator or a person may change it."
            ),
        }
    }


def decide(payload, patterns):
    if payload.get("tool_name") not in WRITERS:
        return None
    args = payload.get("tool_input") or {}
    target = args.get("file_path") or args.get("notebook_path")
    if not target:
        return None
    path = relative(target, payload.get("cwd", ""))
    if leaves_the_project(path):
        return deny(path, "is outside the project")
    for pattern in patterns:
        if glob(pattern).match(path):
            return deny(path, f"is a protected path ({pattern})")
    return None


def main():
    rules = json.loads(RULES.read_text(encoding="utf-8"))
    patterns = [rules["board"], *rules["protected"]]
    decision = decide(json.load(sys.stdin), patterns)
    if decision:
        print(json.dumps(decision))
    return 0


if __name__ == "__main__":
    sys.exit(main())
